#!/usr/bin/env python3
"""Seed the database with:
  1. The three real/candidate source documents + their transcribed sections.
  2. The CANDIDATE rules-as-code corpus generated by generate_candidate_rules.py.
  3. A SYNTHETIC approval catalogue + dependency graph (explicitly labelled synthetic
     -- see docs/PROJECT-RESEARCH.md Limitations for why the approval catalogue itself
     is not claimed as a verified legal catalogue).
  4. Demo user accounts for each RBAC role (dev-only credentials; see README).

Run from repo root: `python scripts/seed_real_corpus.py` (after `pip install -e` all
packages and apps/api/requirements.txt), or via `make seed` / the API container.

This script NEVER sets verification_status=VERIFIED itself -- that only happens via
scripts/demo_apply_reviewer_approvals.py calling the same reviewer service function a
real human reviewer would use (docs/architecture/human-verification.md).
"""
import json
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "apps" / "api"))

from app.core.security import hash_password  # noqa: E402
from app.db import Base, SessionLocal, engine  # noqa: E402
from app.models.approvals import Approval, ApprovalDependency  # noqa: E402
from app.models.regulatory import Regulation, RegulationVersion, Rule, RuleVersion, Section, SourceDocument  # noqa: E402
from app.models.users import User  # noqa: E402
from rules_engine import load_rules_dir  # noqa: E402

DATA_DIR = REPO_ROOT / "data"


def seed_source_documents_and_sections(db):
    registry = json.loads((DATA_DIR / "real" / "source_documents" / "registry.json").read_text())
    reg_by_shortcode = {
        "maitri-act-2023": ("The Maharashtra Industry, Trade and Investment Facilitation Act, 2023", "MAITRI-ACT-2023"),
        "maharashtra-industrial-development-act-1961": ("The Maharashtra Industrial Development Act, 1961", "MID-ACT-1961"),
        "maharashtra-khadi-and-village-industries-act-1960": ("The Maharashtra Khadi and Village Industries Act, 1960", "KHADI-ACT-1960"),
    }

    for doc in registry["documents"]:
        if db.get(SourceDocument, doc["id"]):
            continue
        db.add(
            SourceDocument(
                id=doc["id"],
                title=doc["title"],
                jurisdiction=doc["jurisdiction"],
                authority=doc["authority"],
                document_type=doc["document_type"],
                version_label=doc["version_label"],
                content_hash=doc["content_hash_sha256"],
                retrieved_at=doc["retrieved_at"],
                source_url=doc["source_url"],
                file_type="pdf",
                ocr_status="official_text_mirror_used" if doc["extraction_method"] == "official_text_mirror" else "ocr_pending",
                notes=doc["original_upload_status"],
            )
        )

        sections_path = DATA_DIR / "real" / "extracted_text" / doc["id"] / "sections.json"
        sections_data = json.loads(sections_path.read_text())

        name, short_code = reg_by_shortcode[doc["id"]]
        regulation = db.query(Regulation).filter(Regulation.short_code == short_code).first()
        if regulation is None:
            regulation = Regulation(name=name, short_code=short_code, jurisdiction=doc["jurisdiction"])
            db.add(regulation)
            db.flush()

        version = RegulationVersion(
            regulation_id=regulation.id,
            version_label=doc["version_label"],
            source_document_id=doc["id"],
            source_url=doc["source_url"],
            extraction_method="official_text_mirror",
            status="candidate",
            verification_status="CANDIDATE",
            notes=sections_data.get("notes"),
        )
        db.add(version)
        db.flush()

        for s in sections_data["sections"]:
            db.add(
                Section(
                    regulation_version_id=version.id,
                    number=s["number"],
                    heading=s.get("heading"),
                    text=s["text"],
                    source_document_id=doc["id"],
                    source_section=f"Section {s['number']}",
                    source_url=doc["source_url"],
                    extraction_method="official_text_mirror",
                    status="candidate",
                    verification_status="CANDIDATE",
                )
            )
    db.commit()


def seed_candidate_rules(db):
    rules = load_rules_dir(DATA_DIR / "candidate" / "rules")
    for r in rules:
        if db.get(Rule, r.id):
            continue
        rule_row = Rule(id=r.id, name=r.name, jurisdiction=r.jurisdiction)
        db.add(rule_row)
        db.flush()
        db.add(
            RuleVersion(
                rule_id=r.id,
                version=r.version,
                effective_from=r.effective.from_,
                effective_to=r.effective.to,
                rule_body=json.loads(r.model_dump_json()),
                source_document_id=r.source.document,
                source_section=r.source.section,
                source_url=r.source.url,
                extraction_method="ai_candidate",
                confidence=r.confidence,
                status=r.status,
                verification_status="CANDIDATE",
                notes=r.notes,
            )
        )
    db.commit()


# Synthetic approval catalogue -- NOT sourced from the three real Acts (see
# docs/PROJECT-RESEARCH.md Limitations). These IDs are referenced by `requires` in
# some of the candidate rules (process-level approvals genuinely established by the
# Acts) plus additional illustrative licence/consent nodes used to build a realistic,
# branching demo dependency graph for the Approval Graph / Impact Analysis UI.
# applicable_industries=None means "applies broadly, not industry-restricted in this
# illustrative catalogue". Where a subset is given it is a plausible/illustrative
# mapping for demo purposes (e.g. pollution-consent approvals restricted to
# industries with plausible pollution potential) -- NOT a verified legal
# applicability determination. See docs/PROJECT-RESEARCH.md Limitations.
POLLUTION_PRONE_INDUSTRIES = [
    "chemical_manufacturing", "pharmaceutical_manufacturing", "textile",
    "paper_and_printing", "electronics_assembly", "auto_components",
    "plastics_and_packaging", "leather_and_footwear",
]
FACTORY_ACT_INDUSTRIES = [
    "food_processing", "textile", "chemical_manufacturing", "engineering_manufacturing",
    "pharmaceutical_manufacturing", "plastics_and_packaging", "electronics_assembly",
    "auto_components", "paper_and_printing", "furniture_and_wood", "leather_and_footwear",
]

SYNTHETIC_APPROVALS = [
    # (id, name, category, is_synthetic, applicable_industries)
    ("single-window-application", "Single Window System Application", "process", False, None),  # real, MAITRI s.3
    ("empowered-committee-escalation", "Empowered Committee Escalation", "process", False, None),  # real, MAITRI s.5
    ("joint-inspection-scheduling", "Joint/Rationalised Inspection Scheduling", "process", False, None),  # real, MAITRI s.16
    ("midc-plot-allotment", "MIDC Industrial Plot Allotment", "process", False, None),  # real, MID Act s.14
    ("khadi-village-industry-registration", "Khadi & Village Industry Board Registration", "registration", False,
     ["agro_based_village_industry"]),  # real, Khadi Act s.2(f)
    ("consent-to-establish", "Consent to Establish (Pollution Control Board)", "consent", True, POLLUTION_PRONE_INDUSTRIES),
    ("consent-to-operate", "Consent to Operate (Pollution Control Board)", "consent", True, POLLUTION_PRONE_INDUSTRIES),
    ("factory-license", "Factory License", "license", True, FACTORY_ACT_INDUSTRIES),
    ("fire-noc", "Fire No-Objection Certificate", "consent", True, None),
    ("labour-registration", "Labour Department Registration", "registration", True, None),
]

SYNTHETIC_DEPENDENCIES = [
    # (approval, depends_on, dependency_type)
    ("consent-to-operate", "consent-to-establish", "requires"),
    ("factory-license", "consent-to-establish", "requires"),
    ("factory-license", "fire-noc", "requires"),
    ("single-window-application", "consent-to-establish", "informs"),
    ("single-window-application", "factory-license", "informs"),
    ("single-window-application", "consent-to-operate", "informs"),
    ("single-window-application", "labour-registration", "informs"),
]


def seed_synthetic_approval_catalogue(db):
    for approval_id, name, category, is_synthetic, applicable_industries in SYNTHETIC_APPROVALS:
        if db.get(Approval, approval_id):
            continue
        db.add(
            Approval(
                id=approval_id,
                name=name,
                category=category,
                is_synthetic=is_synthetic,
                status="candidate" if not is_synthetic else "candidate",
                verification_status="SYNTHETIC" if is_synthetic else "CANDIDATE",
                applicable_industries=applicable_industries,
                notes=(
                    "Illustrative/synthetic placeholder approval for demo purposes; not sourced "
                    "from the three real Acts in this corpus."
                    if is_synthetic
                    else "Process-level approval directly established by the real source Acts."
                ),
            )
        )
    db.flush()
    for approval_id, depends_on, dep_type in SYNTHETIC_DEPENDENCIES:
        existing = (
            db.query(ApprovalDependency)
            .filter_by(approval_id=approval_id, depends_on_approval_id=depends_on)
            .first()
        )
        if existing:
            continue
        db.add(
            ApprovalDependency(
                approval_id=approval_id,
                depends_on_approval_id=depends_on,
                dependency_type=dep_type,
                is_synthetic=True,
                dependency_confidence=0.6,
                verification_status="SYNTHETIC",
                notes="Synthetic dependency for demo/dev purposes.",
            )
        )
    db.commit()


DEMO_USERS = [
    ("admin@permitgraph.dev", "ADMIN", "Admin"),
    ("reviewer@permitgraph.dev", "REGULATORY_REVIEWER", "Regulatory Reviewer"),
    ("officer@permitgraph.dev", "OFFICER", "Officer"),
    ("business@permitgraph.dev", "BUSINESS_USER", "Business User"),
    ("developer@permitgraph.dev", "DEVELOPER", "Developer"),
    ("readonly@permitgraph.dev", "READ_ONLY", "Read Only"),
]
DEMO_PASSWORD = "permitgraph-dev-only"  # noqa: S105 -- documented dev-only credential, see README


def seed_users(db):
    for email, role, display_name in DEMO_USERS:
        if db.query(User).filter(User.email == email).first():
            continue
        db.add(
            User(
                email=email,
                password_hash=hash_password(DEMO_PASSWORD),
                role=role,
                display_name=display_name,
            )
        )
    db.commit()


def main():
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        seed_source_documents_and_sections(db)
        seed_candidate_rules(db)
        seed_synthetic_approval_catalogue(db)
        seed_users(db)
        print("Seed complete.")
        print(f"  Source documents: {db.query(SourceDocument).count()}")
        print(f"  Regulations: {db.query(Regulation).count()}")
        print(f"  Sections: {db.query(Section).count()}")
        print(f"  Rules: {db.query(Rule).count()} (all CANDIDATE until reviewed)")
        print(f"  Approvals: {db.query(Approval).count()}")
        print(f"  Approval dependencies: {db.query(ApprovalDependency).count()}")
        print(f"  Demo users: {db.query(User).count()} "
              f"(dev-only password: '{DEMO_PASSWORD}' -- NEVER use in production)")
    finally:
        db.close()


if __name__ == "__main__":
    main()
